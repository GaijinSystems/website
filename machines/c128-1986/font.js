function set(lower){
  var S=[];
  for(var c=0;c<128;c++){
    var k;
    if(c===0)k='@';
    else if(c<27)k=String.fromCharCode((lower?96:64)+c);
    else if(c<32)k=['[','£',']','↑','←'][c-27];
    else if(c<64)k=String.fromCharCode(c);
    else if(lower&&c>64&&c<91)k=String.fromCharCode(c);
    else k=(lower&&(c===94||c===95||c===105||c===122)?'h':'g')+c;
    S.push(k);
  }
  return S;
}
